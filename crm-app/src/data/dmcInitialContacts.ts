// Helper function to clean CEO names
function cleanCeoName(name: string | null | undefined): string | null {
  if (!name || name === 'nicht gefunden/ausgewiesen' || name === 'nicht gefunden' || name === 'nicht ausgewiesen') {
    return null;
  }
  
  // Remove prefixes like "Inhaber:", "(KG) Kommanditisten:", etc.
  let cleaned = name
    .replace(/^Inhaber:\s*/i, '')
    .replace(/^\(KG\)\s*Kommanditisten:\s*/i, '')
    .replace(/^Kommanditisten:\s*/i, '')
    .replace(/^Geschäftsführer:\s*/i, '')
    .trim();
  
  // If multiple names separated by ; or , take the first one
  if (cleaned.includes(';')) {
    cleaned = cleaned.split(';')[0].trim();
  }
  if (cleaned.includes(',') && !cleaned.match(/^\d/)) {
    // Only split if it doesn't look like an address
    const parts = cleaned.split(',');
    if (parts.length === 2 && !parts[1].match(/\d/)) {
      cleaned = parts[0].trim();
    }
  }
  
  return cleaned || null;
}

// Helper function to clean phone numbers - take first one if multiple
function cleanPhone(phone: string | null | undefined): string | null {
  if (!phone) return null;
  
  // If multiple numbers separated by comma or semicolon, take first
  const firstPhone = phone.split(/[,;]/)[0].trim();
  return firstPhone || null;
}

